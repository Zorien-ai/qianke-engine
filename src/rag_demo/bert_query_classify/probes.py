PUNCT = set(" \t\r\n？?！!。.，,~～、；;：:「」“”\"'•·…—_-=+*/\\|@#$%^&()[]{}<>《》【】")


def norm(s) -> str:
    """归一化：抹掉空白与标点，用于「探针是否混进训练集」的判断"""
    return "".join(ch for ch in str(s) if ch not in PUNCT)


def probe_norm_set() -> set:
    return {norm(q) for q in SHORT_BIZ_PROBES + LONG_BIZ_PROBES}
